function generate_tables(resultsDir, cfg)
%GENERATE_TABLES Summary and per-case tables from raw_runs.csv.
%
%   GENERATE_TABLES(RESULTSDIR, CFG) writes into RESULTSDIR/tables:
%     summary_by_solver.csv / .tex   per subset and solver: runs, successes,
%         success rate, failures by status, wins per metric (ties count for
%         every tied solver), medians over the cases solved by ALL listed
%         solvers, and total restarts.
%     results_wide.csv               one row per case, Iter/FuncEvals/
%         ElapsedSec/FinalResidual/status for every solver.
%     detail_<group>.tex             longtables per metric (general, spd):
%         problem, n, start and one column per solver; failures are "F",
%         runs not attempted because of a dimension cap are "NR".
%     restart_statistics.csv         per problem and dimension: runs and
%         total restarts of each solver that restarts.
%     failure_breakdown.csv          counts of every status per solver.
%   The LaTeX files need \usepackage{booktabs,longtable}.

T = load_benchmark_results(fullfile(resultsDir, 'raw_runs.csv'));
outDir = fullfile(resultsDir, 'tables');
if ~exist(outDir, 'dir'), mkdir(outDir); end
solverNames = ordered_solvers(T, cfg);
subsets = benchmark_subsets(T, cfg);

summary_table(T, subsets, solverNames, cfg, outDir);
wide_table(T, solverNames, outDir);
for group = ["general", "spd"]
    Tg = T(T.group == group, :);
    if height(Tg) > 0
        detail_tables(Tg, solverNames, char(group), outDir);
    end
end
restart_table(T, outDir);
statusCounts = groupcounts(T, {'solver', 'status'});
writetable(statusCounts, fullfile(outDir, 'failure_breakdown.csv'));
end

% ======================================================================
function summary_table(T, subsets, solverNames, cfg, outDir)
metrics = cfg.analysis.metrics;
rows = {};
for b = 1:numel(subsets)
    Ts = T(subsets(b).mask, :);
    caseIds = unique(Ts.case_id);
    nc = numel(caseIds);
    [~, ci] = ismember(Ts.case_id, caseIds);
    cost = struct();
    for m = 1:numel(metrics)
        cost.(metrics{m}) = Inf(nc, numel(solverNames));
    end
    solved = false(nc, numel(solverNames));
    for s = 1:numel(solverNames)
        r = find(Ts.solver == solverNames{s});
        solved(ci(r(Ts.success(r))), s) = true;
        for m = 1:numel(metrics)
            v = Inf(numel(r), 1);
            ok = Ts.success(r);
            v(ok) = max(Ts.(metrics{m})(r(ok)), cfg.analysis.metricFloor.(metrics{m}));
            cost.(metrics{m})(ci(r), s) = v;
        end
    end
    common = all(solved, 2);
    for s = 1:numel(solverNames)
        r = Ts.solver == solverNames{s};
        row = {subsets(b).name, solverNames{s}, nc, sum(solved(:, s)), ...
            100 * sum(solved(:, s)) / nc, sum(r & Ts.status == "max_iterations"), ...
            sum(r & Ts.status == "max_function_evaluations"), ...
            sum(r & ~Ts.success & ~ismember(Ts.status, ...
            ["max_iterations", "max_function_evaluations"])), ...
            sum(Ts.restarts(r), 'omitnan'), sum(common)};
        for m = 1:numel(metrics)
            c = cost.(metrics{m});
            best = min(c, [], 2);
            wins = sum(isfinite(best) & c(:, s) == best);
            med = NaN;
            if any(common), med = median(c(common, s)); end
            row = [row, {wins, med}]; %#ok<AGROW>
        end
        rows(end+1, :) = row; %#ok<AGROW>
    end
end
names = {'subset', 'solver', 'cases', 'solved', 'solved_percent', ...
    'fail_max_iterations', 'fail_max_function_evaluations', 'fail_other', ...
    'total_restarts', 'commonly_solved_cases'};
for m = 1:numel(metrics)
    names = [names, {['wins_' metrics{m}], ['median_common_' metrics{m}]}]; %#ok<AGROW>
end
S = cell2table(rows, 'VariableNames', names);
writetable(S, fullfile(outDir, 'summary_by_solver.csv'));

fid = fopen(fullfile(outDir, 'summary_by_solver.tex'), 'w');
cleanup = onCleanup(@() fclose(fid));
fprintf(fid, '%% Generated by generate_tables.m from raw_runs.csv. Wins: ties count for all tied solvers.\n');
fprintf(fid, '%% Medians are over the cases solved by every listed solver.\n');
fprintf(fid, '\\begin{table}[ht]\n\\centering\\small\n');
fprintf(fid, '\\caption{Summary of the benchmark results.}\\label{tab:summary}\n');
fprintf(fid, '\\resizebox{\\linewidth}{!}{%%\n\\begin{tabular}{llrrr%s}\n\\toprule\n', ...
    repmat('rr', 1, numel(metrics)));
fprintf(fid, 'Set & Solver & Cases & Solved & \\%%');
for m = 1:numel(metrics)
    fprintf(fid, ' & Wins %s & Med.\\ %s', cfg.analysis.metricLabels{m}, ...
        cfg.analysis.metricLabels{m});
end
fprintf(fid, ' \\\\\n\\midrule\n');
for i = 1:height(S)
    fprintf(fid, '%s & \\texttt{%s} & %d & %d & %.1f', ...
        strrep(S.subset{i}, '_', '\_'), strrep(S.solver{i}, '_', '\_'), ...
        S.cases(i), S.solved(i), S.solved_percent(i));
    for m = 1:numel(metrics)
        fprintf(fid, ' & %d & %s', S.(['wins_' metrics{m}])(i), ...
            fmt_num(S.(['median_common_' metrics{m}])(i), metrics{m}));
    end
    fprintf(fid, ' \\\\\n');
    if i < height(S) && ~strcmp(S.subset{i}, S.subset{i+1})
        fprintf(fid, '\\midrule\n');
    end
end
fprintf(fid, '\\bottomrule\n\\end{tabular}}\n\\end{table}\n');
end

function wide_table(T, solverNames, outDir)
caseIds = unique(T.case_id, 'stable');
first = arrayfun(@(c) find(T.case_id == c, 1), caseIds);
W = table(caseIds, T.group(first), T.problem(first), T.dimension(first), ...
    T.start(first), 'VariableNames', {'case_id', 'group', 'problem', 'dimension', 'start'});
[~, ci] = ismember(T.case_id, caseIds);
for s = 1:numel(solverNames)
    r = find(T.solver == solverNames{s});
    it = nan(numel(caseIds), 1); fe = it; tm = it; res = it;
    st = strings(numel(caseIds), 1);
    it(ci(r)) = T.iterations(r); fe(ci(r)) = T.function_evaluations(r);
    tm(ci(r)) = T.elapsed_seconds(r); res(ci(r)) = T.final_residual(r);
    st(ci(r)) = T.status(r);
    p = solverNames{s};
    W.([p '_Iter']) = it; W.([p '_FuncEvals']) = fe;
    W.([p '_ElapsedSec']) = tm; W.([p '_FinalResidual']) = res;
    W.([p '_status']) = st;
end
writetable(W, fullfile(outDir, 'results_wide.csv'));
end

function detail_tables(T, solverNames, group, outDir)
specs = {'iterations', 'Iter'; 'function_evaluations', 'FuncEvals'; ...
    'elapsed_seconds', 'ElapsedSec'; 'final_residual', 'FinalResidual'};
caseIds = unique(T.case_id, 'stable');
[~, ci] = ismember(T.case_id, caseIds);
first = arrayfun(@(c) find(T.case_id == c, 1), caseIds);
fid = fopen(fullfile(outDir, sprintf('detail_%s.tex', group)), 'w');
cleanup = onCleanup(@() fclose(fid));
fprintf(fid, '%% Generated by generate_tables.m. "F" = failure (tolerance not met within the budgets).\n');
fprintf(fid, '%% "NR" = not run (gnbfgs, n above its dimension cap).\n');
fprintf(fid, '%% "--" = run absent from raw_runs.csv. Requires booktabs and longtable.\n');
for k = 1:size(specs, 1)
    metric = specs{k, 1};
    fprintf(fid, '{\\footnotesize\n\\begin{longtable}{llr%s}\n', repmat('r', 1, numel(solverNames)));
    fprintf(fid, '\\caption{%s for the %s problems.}\\label{tab:%s_%s}\\\\\n', ...
        specs{k, 2}, upper_first(group), group, metric);
    header = ['\toprule Problem & Start & $n$', ...
        sprintf(' & \\texttt{%s}', strrep(strjoin(solverNames, '|'), '_', '\_'))];
    header = strrep(header, '|', '} & \texttt{');
    fprintf(fid, '%s \\\\\n\\midrule\n\\endfirsthead\n', header);
    fprintf(fid, '%s \\\\\n\\midrule\n\\endhead\n\\bottomrule\n\\endfoot\n', header);
    values = strings(numel(caseIds), numel(solverNames));
    values(:) = "--";
    for s = 1:numel(solverNames)
        r = find(T.solver == solverNames{s});
        for j = r'
            if T.status(j) == "not_run_dimension_cap"
                values(ci(j), s) = "NR";
            elseif T.success(j) || strcmp(metric, 'final_residual')
                values(ci(j), s) = fmt_num(T.(metric)(j), metric);
            else
                values(ci(j), s) = "F";
            end
        end
    end
    for c = 1:numel(caseIds)
        fprintf(fid, '%s & %s & %d', T.problem(first(c)), T.start(first(c)), ...
            T.dimension(first(c)));
        fprintf(fid, ' & %s', values(c, :));
        fprintf(fid, ' \\\\\n');
    end
    fprintf(fid, '\\end{longtable}}\n\n');
end
end

function restart_table(T, outDir)
R = T(T.restarts > 0 | ismember(T.solver, unique(T.solver(T.restarts > 0))), :);
if height(R) == 0
    R = table(strings(0,1), strings(0,1), zeros(0,1), zeros(0,1), zeros(0,1), ...
        'VariableNames', {'solver', 'problem', 'dimension', 'runs', 'total_restarts'});
else
    R = groupsummary(R, {'solver', 'problem', 'dimension'}, 'sum', 'restarts');
    R.Properties.VariableNames{'GroupCount'} = 'runs';
    R.Properties.VariableNames{'sum_restarts'} = 'total_restarts';
end
writetable(R, fullfile(outDir, 'restart_statistics.csv'));
end

function s = fmt_num(v, metric)
if ~isfinite(v)
    s = "--";
elseif strcmp(metric, 'elapsed_seconds')
    s = string(sprintf('%.4f', v));
elseif strcmp(metric, 'final_residual')
    s = string(sprintf('%.2e', v));
elseif v == floor(v)
    s = string(sprintf('%d', v));
else
    s = string(sprintf('%.1f', v));
end
end

function out = upper_first(s)
out = [upper(s(1)) s(2:end)];
if strcmp(s, 'spd'), out = 'SPD'; end
end

function names = ordered_solvers(T, cfg)
present = unique(T.solver);
names = {};
for s = 1:numel(cfg.solvers)
    if any(present == cfg.solvers(s).name)
        names{end+1} = cfg.solvers(s).name; %#ok<AGROW>
    end
end
extra = setdiff(cellstr(present), names);
names = [names, extra(:)'];
end
