function registry = problem_registry()
%PROBLEM_REGISTRY Metadata for every benchmark problem.
%
%   REGISTRY = PROBLEM_REGISTRY() returns a struct array with fields
%     id              integer identifier (1..15)
%     name            short name used in logs ('P01', ...)
%     title           descriptive title
%     group           'general' (P1-P10) or 'spd' (P11-P15)
%     F               residual function handle x -> F(x)
%     minDimension    smallest admissible n
%     excludedStarts  start indices (1..10) not used for this problem
%     definition      LaTeX formula used in the manuscript/tables
%     notes           remarks (domain, structure, known solution)
%
%   To ADD A PROBLEM: write problem_PXX.m with signature F = problem_PXX(x)
%   (column vector in, column vector out), then append one entry below with
%   add(...). Nothing else in the framework needs to change; select it via
%   cfg.problemIds in BENCHMARK_CONFIG.

registry = struct('id', {}, 'name', {}, 'title', {}, 'group', {}, 'F', {}, ...
    'minDimension', {}, 'excludedStarts', {}, 'definition', {}, 'notes', {});

    function add(id, title, group, fun, minDim, excluded, definition, notes)
        registry(end + 1) = struct('id', id, 'name', sprintf('P%02d', id), ...
            'title', title, 'group', group, 'F', fun, 'minDimension', minDim, ...
            'excludedStarts', excluded, 'definition', definition, 'notes', notes);
    end

add(1, 'Modified exponential function', 'general', @problem_P01, 1, [], ...
    'F_1=e^{x_1}-1,\ F_i=e^{x_i}+x_i-1\ (i=2,\dots,n)', ...
    '');
add(2, 'Logarithmic function', 'general', @problem_P02, 1, 8, ...
    'F_i=\log(x_i+1)-x_i/n', ...
    'Domain x_i>-1; guess8=-1 excluded.');
add(3, 'Strictly convex function II', 'general', @problem_P03, 1, [], ...
    'F_i=e^{x_i}-1', '');
add(4, 'Modified strictly convex function II', 'general', @problem_P04, 1, [], ...
    'F_i=\frac{i}{n+1}e^{x_i}-1', '');
add(5, 'Tridiagonal exponential function', 'general', @problem_P05, 2, [], ...
    'F_i=x_i-\exp(\cos(h(x_{i-1}+x_i+x_{i+1}))),\ h=1/(n+1)', '');
add(6, 'Engval symmetric nonlinear equation', 'general', @problem_P06, 2, [], ...
    'F_i=x_i(x_{i-1}^2+2x_i^2+x_{i+1}^2)-1,\ F_n=x_n(x_{n-1}^2+x_n^2)', ...
    'As in Li-Fukushima 1999, Problem 2.');
add(7, 'Trigexp function', 'general', @problem_P07, 2, [], ...
    'F_i=-x_{i-1}e^{x_{i-1}-x_i}+x_i(4+3x_i^2)+2x_{i+1}+\sin(x_i-x_{i+1})\sin(x_i+x_{i+1})-8', '');
add(8, 'Modified trigonometric function', 'general', @problem_P08, 1, [], ...
    'F_i=2[n+i(1-\cos x_i)-\sin x_i-\cos x_i](2\sin x_i-\cos x_i)', ...
    'Unbounded level sets (outside Assumption 1).');
add(9, 'Function derived from the Chandrasekhar H-equation', 'general', @problem_P09, 1, [], ...
    'F_i=x_i-\dfrac{4}{c\,n\,(\delta^{\top}x)\sum_j\delta_j^{-1}},\ \delta_j=\frac{j-1/2}{n},\ c=0.9', ...
    'Not the componentwise H-equation (Kelley 1980); see problem_P09.m.');
add(10, 'Broyden tridiagonal function', 'general', @problem_P10, 2, [], ...
    'F_i=(3-2x_i)x_i-x_{i-1}-2x_{i+1}+1', 'h=2.');
add(11, 'Symmetric sine boundary-value problem', 'spd', @problem_P11, 2, [], ...
    'F(x)=A_8x+\sin x-\mathbf{1},\ A_8=\mathrm{tridiag}(-1,8,-1)', '5I<=J<=11I.');
add(12, 'Diagonal sine problem', 'spd', @problem_P12, 1, [], ...
    'F_i=2x_i-\sin x_i', 'I<=J<=3I.');
add(13, 'Symmetric linear tridiagonal problem', 'spd', @problem_P13, 2, [], ...
    'F(x)=\mathrm{tridiag}(1,\tfrac52,1)\,x-\mathbf{1}', '(1/2)I<=J<=(9/2)I.');
add(14, 'Coupled sine-diffusion problem', 'spd', @problem_P14, 2, [], ...
    'F(x)=A_4(x-r)+\sin x-\sin r,\ r_i=\frac{i}{n+1}', 'I<=J<=7I; x*=r.');
add(15, 'Coupled tanh-diffusion problem', 'spd', @problem_P15, 2, [], ...
    'F(x)=A_4(x-r)+\tanh x-\tanh r,\ r_i=\frac{i}{n+1}', '2I<=J<=7I; x*=r.');

ids = [registry.id];
if numel(unique(ids)) ~= numel(ids)
    error('bm:registry', 'Duplicate problem identifiers in PROBLEM_REGISTRY.');
end
end
